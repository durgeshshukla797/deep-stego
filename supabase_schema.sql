-- 1. Create PROFILES table
create table if not exists public.profiles (
  id uuid references auth.users on delete cascade primary key,
  username text not null,
  stego_id text unique not null,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- Enable RLS for profiles
alter table public.profiles enable row level security;

-- Policies for profiles
create policy "Allow all authenticated and anon users to read profiles"
  on public.profiles for select
  using (true);

create policy "Allow users to insert their own profile"
  on public.profiles for insert
  with check (true);

create policy "Allow users to update their own profile"
  on public.profiles for update
  using (auth.uid() = id);

-- 2. Create MESSAGES table
create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  sender_id uuid references public.profiles(id) on delete cascade not null,
  receiver_id uuid references public.profiles(id) on delete cascade not null,
  stego_path text not null,
  note text,
  revealed boolean default false not null,
  passphrase_hash text default 'no',
  encryption_iv text,
  sender_public_key text,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- Enable RLS for messages
alter table public.messages enable row level security;

-- Policies for messages
create policy "Users can view messages sent by them or sent to them"
  on public.messages for select
  using (auth.uid() = sender_id or auth.uid() = receiver_id);

create policy "Users can insert messages"
  on public.messages for insert
  with check (auth.uid() = sender_id);

create policy "Receiver can update revealed status"
  on public.messages for update
  using (auth.uid() = receiver_id);

-- 3. Create Storage Bucket for Stego Images
insert into storage.buckets (id, name, public)
values ('stego-images', 'stego-images', false)
on conflict (id) do nothing;

-- Storage policies
create policy "Authenticated users can upload stego images"
  on storage.objects for insert
  with check (bucket_id = 'stego-images');

create policy "Users can read stego images"
  on storage.objects for select
  using (bucket_id = 'stego-images');
